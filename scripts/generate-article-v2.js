function detectCategory(title) {
  const lower = title.toLowerCase();

  if (lower.includes("подъемник") || lower.includes("подъёмник")) {
    return "Подъемники";
  }

  if (lower.includes("погрузчик")) {
    return "Погрузчики";
  }

  if (lower.includes("экскаватор")) {
    return "Экскаваторы";
  }

  return "Техника";
}
function detectEquipmentType(title) {
  const lower = title.toLowerCase();

  if (lower.includes("экскаватор")) return "excavator";
  if (lower.includes("ножнич")) return "scissorLift";
  if (lower.includes("телескоп")) return "telehandler";
  if (lower.includes("коленчат")) return "boomLift";
  if (lower.includes("мини-погрузчик")) return "skidSteer";
  if (lower.includes("вилоч")) return "forklift";

  return "general";
}
