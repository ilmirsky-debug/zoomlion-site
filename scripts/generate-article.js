const fs = require("fs");
const path = require("path");

function transliterate(text) {
  const map = {
    а: "a", б: "b", в: "v", г: "g", д: "d", е: "e", ё: "e",
    ж: "zh", з: "z", и: "i", й: "j", к: "k", л: "l", м: "m",
    н: "n", о: "o", п: "p", р: "r", с: "s", т: "t", у: "u",
    ф: "f", х: "h", ц: "c", ч: "ch", ш: "sh", щ: "sch",
    ъ: "", ы: "y", ь: "", э: "e", ю: "yu", я: "ya",
  };

  return text
    .toLowerCase()
    .split("")
    .map((char) => map[char] ?? char)
    .join("");
}

function slugify(text) {
  return transliterate(text)
    .replace(/[^a-z0-9]+/gi, "-")
    .replace(/^-|-$/g, "");
}

function toImportName(slug) {
  return (
    slug
      .split("-")
      .map((part, index) =>
        index === 0 ? part : part.charAt(0).toUpperCase() + part.slice(1)
      )
      .join("") + "Article"
  );
}

function updateBlogIndex(slug) {
  const indexPath = path.join(__dirname, "../content/blog/index.js");
  const importName = toImportName(slug);
  const importLine = `import { article as ${importName} } from "./${slug}";`;

  let content = fs.readFileSync(indexPath, "utf8");

  if (!content.includes(importLine)) {
    content = importLine + "\n" + content;
  }

  const entryLine = `  [${importName}.slug]: ${importName},`;

  if (!content.includes(entryLine)) {
    content = content.replace(
      /export const articles = \{\n/,
      `export const articles = {\n${entryLine}\n`
    );
  }

  fs.writeFileSync(indexPath, content);
}

function detectCategory(title) {
  const lower = title.toLowerCase();

  if (lower.includes("подъемник") || lower.includes("подъёмник")) {
    return "Подъемники";
  }

  if (lower.includes("сервис") || lower.includes("обслуживание") || lower.includes("ремонт")) {
    return "Сервис";
  }

  return "Погрузчики";
}

function detectImage(title) {
  const lower = title.toLowerCase();

  if (lower.includes("ножнич")) return "/hero4.png";
  if (lower.includes("коленчат")) return "/hero4.png";
  if (lower.includes("телескоп")) return "/hero1.png";
  if (lower.includes("дизель")) return "/hero2.png";
  if (lower.includes("электр")) return "/hero3.png";

  return "/hero1.png";
}

function cleanTopic(title) {
  return title
    .toLowerCase()
    .replace(/:.*/g, "")
    .replace(/\?.*/g, "")
    .replace("как выбрать", "")
    .trim();
}

